            import sys

            device_code = sys.argv[1]
            current_pid = os.getpid()
            matches = []
            for name in os.listdir("/proc"):
                if not name.isdigit():
                    continue

                pid = int(name)
                if pid == current_pid:
                    continue

                try:
                    cmdline = open(f"/proc/{pid}/cmdline", "rb").read().replace(b"\0", b" ").decode("utf-8", "ignore")
                    environ = open(f"/proc/{pid}/environ", "rb").read().replace(b"\0", b"\n").decode("utf-8", "ignore")
                except OSError:
                    continue

                if "main.py" not in cmdline:
                    continue

                if f"SENTRIBEE_INSTANCE={device_code}" in environ or device_code in cmdline:
                    matches.append(str(pid))

            print(" ".join(matches))
            PY
            )"
            if [ -n "$old_pids" ]; then
              echo "Stopping previous runtime processes for $device_code: $old_pids" >> "$instance_dir/runtime.log"
              kill $old_pids 2>/dev/null || true
              sleep 1
              kill -9 $old_pids 2>/dev/null || true
            fi

            cd "$main_dir"
            python_bin="$root/venv/bin/python"
            if [ ! -x "$python_bin" ]; then
              python_bin="$root/.venv/bin/python"
            fi
            if [ ! -x "$python_bin" ]; then
              python_bin="$(command -v python3)"
            fi
            if [ -z "$python_bin" ] || [ ! -x "$python_bin" ]; then
              echo "No Python runtime found. Expected $root/venv/bin/python, $root/.venv/bin/python, or python3." >&2
              exit 21
            fi

            {
              echo "Starting at $(date -Is)"
              echo "Device: $device_code"
              echo "Main: $main_path"
              echo "Env: $env_file"
              echo "Python: $python_bin"
            } >> "$instance_dir/runtime.log"
            nohup env SENTRIBEE_INSTANCE="$device_code" SENTRIBEE_INSTANCE_ENV="$env_file" SENTRIBEE_ENV_FILE="$env_file" OPENAI_API_KEY="$managed_openai_api_key" OPENAI_MODEL="$managed_openai_model" OPENAI_BASE_URL="$managed_openai_base_url" "$python_bin" "$main_path" >> "$instance_dir/runtime.log" 2>&1 &
            echo "Start command sent to $(hostname) for $device_code using $python_bin."
            """;
    }

    private static string ShellQuote(string value)
    {
        return $"'{value.Replace("'", "'\"'\"'", StringComparison.Ordinal)}'";
    }

    private static bool IsEditableEnvironmentKey(string key)
    {
        return !AutoGeneratedEnvironmentKeys.Contains(key) &&
            !ManagedHiddenEnvironmentKeys.Contains(key) &&
            !key.StartsWith("OPENAI_", StringComparison.OrdinalIgnoreCase);
    }
